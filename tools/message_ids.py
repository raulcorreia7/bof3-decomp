#!/usr/bin/env python3
"""Generate include/menu/message_ids.h from the literal message ids in src/.

A message id is an index into the area message table (include/menu/gameui.h). The
scan recognises the id argument of every call, macro and write that carries one:

    Message_StartAreaMessage, Message_Request, Scene_ShowMessage,
    MESSAGE_START_WAIT, SCENE_MESSAGE_WAIT, SCENA14_START_AREA_MESSAGE,
    WORLD_ARM_ANSWER_MESSAGE, WORLD_ARM_ANSWER_MESSAGE_IDLE,
    MESSAGE_TABLE_TEXT(AREA_MESSAGE_TABLE, ...),
    func_801D0DD4, func_801D10AC, and `g_MessageRequest = <id>`.

Comments and string literals are ignored. The distinct values become one numbered
define each, in decimal, sorted; uses of the names are collected too, so a value
stays in the header after its last literal is rewritten. MESSAGE_NONE (0xFFFF)
keeps its name.

    tools/message_ids.py            write the header
    tools/message_ids.py --check    exit 1 when the header is stale
    tools/message_ids.py --list     print the values and their sites
    tools/message_ids.py --rewrite  rewrite the literal sites to the names
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "include/menu/message_ids.h"
SOURCES = ROOT / "src"
SUFFIXES = (".c", ".h", ".inc")

NUMBER = r"(?:0[xX][0-9A-Fa-f]+|\d+)[uUlL]*"
MESSAGE_NONE = 0xFFFF
FIRST_ARG = (
    "Message_StartAreaMessage",
    "Message_Request",
    "Scene_ShowMessage",
    "MESSAGE_START_WAIT",
    "SCENE_MESSAGE_WAIT",
    "SCENA14_START_AREA_MESSAGE",
    "WORLD_ARM_ANSWER_MESSAGE",
    "func_801D0DD4",
    "func_801D10AC",
)
FIRST_ARG_RE = re.compile(
    r"\b(" + "|".join(FIRST_ARG) + r")\s*\(\s*(" + NUMBER + r")\b"
)
IDLE_RE = re.compile(
    r"\bWORLD_ARM_ANSWER_MESSAGE_IDLE\s*\(\s*("
    + NUMBER
    + r")\s*,\s*("
    + NUMBER
    + r")\s*\)"
)
TEXT_RE = re.compile(
    r"\bMESSAGE_TABLE_TEXT\s*\(\s*AREA_MESSAGE_TABLE\s*,\s*(" + NUMBER + r")\s*\)"
)
WRITE_RE = re.compile(r"\bg_MessageRequest\s*=\s*(" + NUMBER + r")\s*;")
NAME_RE = re.compile(r"\bMSG_(\d+)\b")
MASK_RE = re.compile(
    r"/\*.*?\*/|//[^\n]*|\"(?:\\.|[^\"\\\n])*\"|'(?:\\.|[^'\\\n])*'", re.DOTALL
)


def to_int(text: str) -> int:
    """Parse a C integer literal, dropping any u/l suffix."""
    return int(text.rstrip("uUlL"), 0)


def masked(text: str) -> str:
    """Blank comments and string literals, keeping offsets and newlines."""
    return MASK_RE.sub(lambda match: re.sub(r"[^\n]", " ", match.group(0)), text)


def sites(text: str) -> list[tuple[int, int, int, bool]]:
    """Return (first offset, last offset, value, is_name) for every message id."""
    found = []
    for match in FIRST_ARG_RE.finditer(text):
        found.append((match.start(2), match.end(2), to_int(match.group(2)), False))
    for match in IDLE_RE.finditer(text):
        for group in (1, 2):
            found.append(
                (
                    match.start(group),
                    match.end(group),
                    to_int(match.group(group)),
                    False,
                )
            )
    for match in TEXT_RE.finditer(text):
        found.append((match.start(1), match.end(1), to_int(match.group(1)), False))
    for match in WRITE_RE.finditer(text):
        found.append((match.start(1), match.end(1), to_int(match.group(1)), False))
    for match in NAME_RE.finditer(text):
        found.append((match.start(), match.end(), int(match.group(1), 10), True))
    return [item for item in found if item[2] != MESSAGE_NONE]


def source_files():
    for path in sorted(SOURCES.rglob("*")):
        if path.suffix in SUFFIXES and path.is_file():
            yield path


def scan() -> tuple[dict[int, list[tuple[Path, int]]], int]:
    ids: dict[int, list[tuple[Path, int]]] = defaultdict(list)
    width = 3
    for path in source_files():
        text = masked(path.read_text(encoding="utf-8", errors="surrogateescape"))
        for start, _, value, _ in sites(text):
            ids[value].append((path.relative_to(ROOT), text.count("\n", 0, start) + 1))
            width = max(width, len(str(value)))
    return ids, width


def name(value: int, width: int) -> str:
    return f"MSG_{value:0{width}d}"


def render(ids: dict[int, list[tuple[Path, int]]], width: int) -> str:
    lines = [
        "/* Generated by tools/message_ids.py from the literal message ids in src/.",
        " * Do not edit; regenerate with `python3 tools/message_ids.py`.",
        " * Each value is an index into the area message table (include/menu/gameui.h). */",
        "#ifndef MENU_MESSAGE_IDS_H",
        "#define MENU_MESSAGE_IDS_H",
        "",
    ]
    lines += [f"#define {name(value, width)} {value}" for value in sorted(ids)]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def rewrite_text(text: str, names: dict[int, str]) -> str:
    """Rewrite the literal message ids in `text`; an existing MSG_ name is left alone."""
    new = text
    for start, end, value, is_name in sorted(sites(masked(text)), reverse=True):
        if is_name:
            continue
        new = new[:start] + names[value] + new[end:]
    return new


def rewrite() -> int:
    """Rewrite literal message ids at the recognised sites to the generated names."""
    ids, width = scan()
    names = {value: name(value, width) for value in ids}
    changed = 0
    for path in source_files():
        text = path.read_text(encoding="utf-8", errors="surrogateescape")
        new = rewrite_text(text, names)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed += 1
    print(f"rewrote {changed} file(s)")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail when the header is stale"
    )
    parser.add_argument(
        "--list", action="store_true", help="print each value with its sites"
    )
    parser.add_argument(
        "--rewrite", action="store_true", help="rewrite the literal sites to the names"
    )
    args = parser.parse_args(argv)

    if args.rewrite:
        return rewrite()

    if not SOURCES.is_dir():
        print("message-ids: no src/ to scan")
        return 0

    ids, width = scan()
    if not ids and not HEADER.exists():
        print(f"message-ids: no message ids; {HEADER.relative_to(ROOT)} is not needed")
        return 0
    if args.list:
        for value in sorted(ids):
            print(f"{name(value, width)} {value} ({len(ids[value])} site(s))")
            for path, line_no in ids[value][:3]:
                print(f"    {path}:{line_no}")
        return 0

    text = render(ids, width)
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(
                f"{HEADER.relative_to(ROOT)} is stale; run tools/message_ids.py",
                file=sys.stderr,
            )
            return 1
        print(f"message-ids: {HEADER.relative_to(ROOT)} is current ({len(ids)} ids)")
        return 0

    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(ids)} ids)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
