/* Or-ed into the facing of an area request: only the scroll target is placed
 * (func_801BFF9C) and the map-loading walk flag is set (func_8019FAA0). */
#define AREA_ENTRY_MAP_LOADING 0x80

#define GAME_TABLE_ENTRY_SIZE  0x44

/* AreaLoad.flag_32, the behaviors the area runs in place of the ordinary field
 * code. The game copies it to g_GameRequestFlags at area entry. */
typedef enum AreaLoadFlags {
    AREA_LOAD_FLAG_WORLD_MAP       = 1 << 0, /* the area runs the world map */
    AREA_LOAD_FLAG_FISHING         = 1 << 3, /* the area runs the fishing minigame */
    AREA_LOAD_FLAG_FAIRY_VILLAGE   = 1 << 4,
    AREA_LOAD_FLAG_NO_ACTOR_SCRIPT = 1 << 5, /* actors keep their own mode and request no talk script */
    AREA_LOAD_FLAG_SHOP            = 1 << 6, /* a travelling shop opens with the area */
} AreaLoadFlags;

typedef struct AreaLoad {
    /* 0x00 */ void*     handler;
    /* 0x04 */ u8        pad_04[0x08];
    /* 0x0C */ u8*       unk_0C;
    /* 0x10 */ u8        pad_10[0x22];
    /* 0x32 */ u8        flag_32;
    u8                   pad_33;
    /* 0x34 */ Callback* steps;
    /* 0x38 */ void*     matrix;
    /* 0x3C */ void*     unk_3C;
    /* 0x40 */ Callback  callback;
} AreaLoad;

ASSERT_SIZE(AreaLoad, GAME_TABLE_ENTRY_SIZE);
ASSERT_OFFSET(AreaLoad, handler, 0x00);
ASSERT_OFFSET(AreaLoad, unk_0C, 0x0C);
ASSERT_OFFSET(AreaLoad, flag_32, 0x32);
ASSERT_OFFSET(AreaLoad, steps, 0x34);
ASSERT_OFFSET(AreaLoad, matrix, 0x38);
ASSERT_OFFSET(AreaLoad, unk_3C, 0x3C);
ASSERT_OFFSET(AreaLoad, callback, 0x40);

